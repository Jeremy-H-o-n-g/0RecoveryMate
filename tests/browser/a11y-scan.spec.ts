import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

/**
 * S23 automated accessibility regression: axe-core scans of every core route
 * against the production build. SERIOUS/CRITICAL violations fail the suite
 * (acceptance: 无严重/高可访问性问题). A full HTML report is written to
 * docs/a11y-report-S23.html for evidence.
 */

const ROUTES: { path: string; name: string }[] = [
  { path: "/", name: "home" },
  { path: "/body/ankle", name: "body-ankle" },
  { path: "/body/shoulder", name: "body-shoulder" },
  { path: "/exercise/ankle-inversion-stretch", name: "exercise-detail" },
  { path: "/flow/basketball", name: "flow-basketball" },
  { path: "/flow/archery", name: "flow-archery" },
];

const IMPACT_BLOCKLIST = ["serious", "critical"];

test.describe("axe scans (S23)", () => {
  for (const route of ROUTES) {
    test(`${route.name} (${route.path}) has no serious/critical violations`, async ({
      page,
    }) => {
      await page.goto(route.path);
      const results = await new AxeBuilder({ page })
        .withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"])
        .analyze();

      const blocking = results.violations.filter((v) =>
        v.impact ? IMPACT_BLOCKLIST.includes(v.impact) : false
      );
      const moderate = results.violations.filter((v) => v.impact === "moderate");
      // Visible in the runner output for triage (never silently ignored).
      if (moderate.length > 0) {
        console.log(
          `[a11y][${route.name}] moderate (non-blocking):`,
          moderate.map((m) => m.id).join(", ")
        );
      }

      expect(
        blocking.map((v) => `${v.id} (${v.impact})`),
        `${route.path}: serious/critical axe violations must be zero`
      ).toEqual([]);
    });
  }

  // Evidence report: aggregated results for all routes (runs last).
  test("write a11y-report-S23.html evidence", async ({ page }) => {
    const sections: string[] = [];
    for (const route of ROUTES) {
      await page.goto(route.path);
      const results = await new AxeBuilder({ page })
        .withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa"])
        .analyze();
      sections.push(renderRoute(route, results.violations));
    }
    const html = `<!doctype html><html lang="en"><head><meta charset="utf-8">
<title>RecoverMate a11y report S23</title>
<style>body{font-family:system-ui;margin:2rem;color:#111}table{border-collapse:collapse;margin-top:1rem}td,th{border:1px solid #999;padding:.4rem .8rem;text-align:left;font-size:.9rem}h2{margin-top:2rem}.pass{color:#067d47}.fail{color:#b00}</style>
</head><body><h1>RecoverMate — automated accessibility report (S23)</h1>
<p>axe-core, tags wcag2a/2aa/21a/21aa, production build (next start). Generated by tests/browser/a11y-scan.spec.ts. Blocklist: serious + critical.</p>
${sections.join("\n")}
</body></html>`;
    mkdirSync(join(process.cwd(), "docs"), { recursive: true });
    writeFileSync(join(process.cwd(), "docs", "a11y-report-S23.html"), html, "utf8");
  });
});

function renderRoute(
  route: { path: string; name: string },
  violations: Awaited<ReturnType<AxeBuilder["analyze"]>>["violations"]
): string {
  const blocking = violations.filter((v) =>
    v.impact ? IMPACT_BLOCKLIST.includes(v.impact) : false
  );
  const rows = violations.length
    ? violations
        .map(
          (v) =>
            `<tr><td>${v.id}</td><td>${v.impact ?? "-"}</td><td>${v.help}</td><td>${v.nodes.length}</td></tr>`
        )
        .join("")
    : `<tr><td colspan="4">no violations</td></tr>`;
  return `<h2 class="${blocking.length ? "fail" : "pass"}">${route.name} — ${route.path} — ${
    blocking.length ? "BLOCKING VIOLATIONS" : "PASS"
  }</h2><table><tr><th>rule</th><th>impact</th><th>help</th><th>nodes</th></tr>${rows}</table>`;
}
